#!/usr/bin/env node
/** Parses every JavaScript source file with Node itself. No dependencies. */
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SKIP = new Set(["node_modules", ".git", "data", "dist", ".freebuff"]);

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (/\.m?js$/.test(entry.name)) out.push(full);
  }
  return out;
}

const files = walk(ROOT).sort();
let failed = 0;
for (const file of files) {
  const result = spawnSync(process.execPath, ["--check", file], { encoding: "utf8" });
  if (result.status !== 0) {
    failed += 1;
    console.error(`\n${path.relative(ROOT, file)}`);
    console.error(result.stderr || result.stdout);
  }
}
console.log(`${files.length - failed}/${files.length} files parsed.`);
process.exit(failed ? 1 : 0);
